USE CATALOG MY_CATALOG;
USE SCHEMA MY_SCHEMA;

CREATE TABLE IF NOT EXISTS MY_CATALOG.MY_SCHEMA.BIANOR_REPRESENTATION_CONFIG (
	ID BIGINT NOT NULL,
	NAME VARCHAR(255) NOT NULL,
    SOM_MODEL_LOCATION VARCHAR(255) NOT NULL,
    FEATURE_TABLE_LOCATION VARCHAR(255) NOT NULL,

	PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS MY_CATALOG.MY_SCHEMA.BIANOR_PREDICTION_CONFIG (
    ID BIGINT NOT NULL,
	NAME VARCHAR(255) NOT NULL,
    PREDICTION_TABLE_LOCATION VARCHAR(255) NOT NULL,

	PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS MY_CATALOG.MY_SCHEMA.BIANOR_MAP_REPRESENTATION_PREDICTION_CONFIG (
    REPRESENTATIONC_ID BIGINT NOT NULL,
    PREDICTIONC_ID BIGINT NOT NULL,

    PRIMARY KEY (REPRESENTATIONC_ID, PREDICTIONC_ID),
    FOREIGN KEY (REPRESENTATIONC_ID) REFERENCES BIANOR_REPRESENTATION_CONFIG(ID),
    FOREIGN KEY (PREDICTIONC_ID) REFERENCES BIANOR_PREDICTION_CONFIG(ID)
);
